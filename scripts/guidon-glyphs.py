"""Writes resources/js/lib/guidonGlyphs.js: the outlines of Oswald Medium for the characters a guidon may carry.

The guidon is drawn as an SVG that is shown as an <img> and downloaded as a file, where no web font can reach it, so its
text is drawn as paths from these outlines instead. Run it again only to change the font or the character set:

    pip install fonttools
    python scripts/guidon-glyphs.py

The font comes from the @fontsource/oswald dev dependency (SIL Open Font License 1.1, see its LICENSE file).
"""
import json
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / 'node_modules/@fontsource/oswald/files/oswald-latin-500-normal.woff'
OUT = ROOT / 'resources/js/lib/guidonGlyphs.js'
CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789./- '

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
hmtx = font['hmtx']
out = {}
for ch in CHARS:
    name = cmap[ord(ch)]
    pen = SVGPathPen(glyphs, lambda v: str(round(v)))
    # Font units point up; flip so the path is in SVG's y-down space with the baseline at 0.
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    out[ch] = [hmtx[name][0], pen.getCommands()]

os2 = font['OS/2']
body = json.dumps(out, separators=(',', ':'))
OUT.write_text(
    '// Generated by scripts/guidon-glyphs.py from Oswald Medium (SIL Open Font License 1.1): do not edit by hand.\n'
    '// Each character a guidon may carry, as [advance width, SVG path] in font units, y down, baseline at 0.\n'
    f'export const UNITS_PER_EM = {font["head"].unitsPerEm};\n'
    f'export const CAP_HEIGHT = {os2.sCapHeight};\n'
    f'export const GLYPHS = {body};\n',
    encoding='utf-8',
)
print(OUT, len(body))
